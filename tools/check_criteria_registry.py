"""INVARIANT: every criteria key a transform emits is defined, once, in the criteria-key registry.

THE RULE. A criteria key is a contract between three repos. Transformations emits it,
Integration-Service maps an integration's RTA row to it, and Token-Service extracts
transformedResponse[key] by exact, case-sensitive match and compares it against a requirement.
Categories have one authoritative definition (Integration-Service's IntegrationCategories,
GET /integration/enum/products). Criteria keys had none, which is how they drifted:
`isMFAEnabled` carries five incompatible meanings across eight integrations,
`requiredCoveragePercentage` is a boolean at two vendors and a percentage at ten, and
`isEPPConfigured` is a percentage at fourteen and a boolean at six -- so no requirement bar fits
both halves of the estate. contracts/criteria-registry/keys/<key>.json is that one definition.

WHAT THIS CHECKS, three things, each behind the same may-only-shrink ratchet the sibling
contracts use:

  1. SCHEMA. Every registry entry validates against criteria-key.schema.json, plus the rules
     a schema cannot express: the file is named after the key; names and aliases are unique
     case-insensitively (a one-letter case difference is a different key to Token-Service and
     the same file to a case-insensitive filesystem); validation.level is the MINIMUM across
     implementations; a deprecated key names a registered successor. Schema failures are never
     allowlisted -- a malformed entry is fixed, not waived.

  2. UNREGISTERED KEYS. Each transform under safeguards/ is executed in the production
     RestrictedPython sandbox against two bodies that carry no evidence -- {} and a body whose
     every read raises -- and the keys of the transformedResponse it returns are read OFF THE
     RESULT, never off the filename (`isssorequired.py` yields isSsorequired, never
     isSSORequired; the mapping is lossy). A criterion-shaped key (see _is_criterion_shaped)
     with no registry entry and no alias is a finding.

  3. TYPE. For a registered key whose status is not `contested`, every value observed on
     those bodies must be null or the declared valueType. A bool is not a number here, because
     Conditions.greaterThan coerces with int(float(x)) and int(float(False)) is 0 -- the exact
     mechanism by which an unreadable coverage figure clears a "fewer than N" bar. A contested
     key's type is NOT enforced (the registry has not ruled); its observed type split is
     printed instead, as evidence for whoever rules.

WHAT THIS DOES NOT CHECK, stated so a green run is not over-read:

  * Success-path values. The two bodies prove nothing, so a transform whose success branch
    returns a bool under a numeric key is invisible here (BeyondTrust and DopeSecurity's
    requiredCoveragePercentage are exactly that). Those are caught by the registry entry's
    replay-backed implementation records, not by CI.
  * Whether a registered key MEANS what its entry says. That is what the entry's citations and
    V-level are for. The registry's defence against a confident wrong entry is not the field;
    it is the evidence the field is required to cite.
  * Which integration may answer a key. That needs the RTA, which lives in Integration-Service;
    integrationPolicy/allowedIntegrations is enforced there (contracts/criteria-registry/
    README.md, "Who enforces what").

THE RATCHET. contracts/criteria-registry-allowlist.json is generated by --emit-allowlist, never
by hand, and MAY ONLY SHRINK. Instances are `<file>::<key>` (unregistered) and
`<file>::<key>::<type>` (type). A listed instance is reported and does not fail the run; an
unlisted one does; a listed one that no longer reproduces is reported STALE so the list keeps
moving. Registering a key is how its instances leave the list.

USAGE
    python tools/check_criteria_registry.py
    python tools/check_criteria_registry.py --self-test
    python tools/check_criteria_registry.py --emit-allowlist
    python tools/check_criteria_registry.py --schema-only
"""
from __future__ import annotations

import argparse
import json
